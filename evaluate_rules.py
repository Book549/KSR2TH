"""Evaluate the rule-based translator, on the same files the neural model uses.

    python evaluate_rules.py

Reports BLEU and chrF on each split PLUS the numbers that actually matter for
a rule system: dictionary coverage, and how often the output is exact.

Read the splits differently. `test.jsonl` is generated by the same templates
the neural model trained on, so it flatters BOTH systems - the rule engine and
the generator draw on overlapping vocabulary. `test_unseen_vocab.jsonl`
contains words held out of neural training entirely; the rule engine has no
"training" to hold anything out of, so its score there is simply its score on
ordinary dictionary words. That asymmetry is the point: a rule engine has no
train/test distinction, which is exactly why it degrades gracefully.
"""
from __future__ import annotations

import json
import os
import sys

import sacrebleu

from rules.reverse import KarenToThai
from rules.translator import RuleTranslator

SPLITS = ["test.jsonl", "test_unseen_vocab.jsonl"]
DATA_DIR = "generated_dataset"


def load(path: str):
    with open(path, "r", encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def main() -> None:
    rt = RuleTranslator()
    kt = KarenToThai(rt.lex)
    print(f"Lexicon: {len(rt.lex)} Thai headwords / {len(kt.rev)} Karen headwords, "
          f"{len(rt.names)} proper names\n")

    summary = {}
    for split in SPLITS:
        path = os.path.join(DATA_DIR, split)
        if not os.path.exists(path):
            print(f"(skipping {split} - not found)")
            continue
        rows = load(path)
        limit = int(sys.argv[1]) if len(sys.argv) > 1 else len(rows)
        rows = rows[:limit]

        hyps, refs, coverages, exact = [], [], [], 0
        full_coverage = 0
        for r in rows:
            t = rt.translate(r["thai"])
            hyps.append(t.karen)
            refs.append(r["sgaw_karen"])
            coverages.append(t.coverage)
            if t.coverage == 1.0:
                full_coverage += 1
            if t.karen.strip() == r["sgaw_karen"].strip():
                exact += 1

        bleu = sacrebleu.corpus_bleu(hyps, [refs]).score
        chrf = sacrebleu.corpus_chrf(hyps, [refs]).score
        summary[split] = {
            "rows": len(rows),
            "bleu": round(bleu, 2),
            "chrf": round(chrf, 2),
            "exact_match_pct": round(100 * exact / max(1, len(rows)), 1),
            "mean_dictionary_coverage_pct": round(100 * sum(coverages) / max(1, len(coverages)), 1),
            "fully_covered_sentences_pct": round(100 * full_coverage / max(1, len(rows)), 1),
        }
        print(f"=== {split}  ({len(rows)} rows) ===")
        for k, v in summary[split].items():
            print(f"    {k:34} {v}")
        print()

    # ------------------------------------------------------------------
    # Reverse direction, plus a round trip.
    #
    # The round trip is the honest stress test: Thai -> Karen -> Thai passes
    # through BOTH rule sets and every lossy step compounds. Karen carries
    # only one general classifier and no politeness particles, so some Thai
    # detail cannot survive the trip by construction - the score is a floor
    # on quality, not a measure of either direction on its own.
    # ------------------------------------------------------------------
    for split in SPLITS:
        path = os.path.join(DATA_DIR, split)
        if not os.path.exists(path):
            continue
        rows = load(path)[: (int(sys.argv[1]) if len(sys.argv) > 1 else None)]

        back, gold, cov, exact = [], [], [], 0
        rt_hyp, rt_exact = [], 0
        for r in rows:
            t = kt.translate(r["sgaw_karen"])
            back.append(t.thai); gold.append(r["thai"]); cov.append(t.coverage)
            if t.thai.strip() == r["thai"].strip():
                exact += 1
            round_trip = kt.translate(rt.translate(r["thai"]).karen).thai
            rt_hyp.append(round_trip)
            if round_trip.strip() == r["thai"].strip():
                rt_exact += 1

        # Thai has no spaces, so word-level BLEU is close to meaningless here;
        # chrF is character-based and is the number to read.
        summary[f"{split} [kr2th]"] = {
            "rows": len(rows),
            "chrf": round(sacrebleu.corpus_chrf(back, [gold]).score, 2),
            "exact_match_pct": round(100 * exact / max(1, len(rows)), 1),
            "mean_dictionary_coverage_pct": round(100 * sum(cov) / max(1, len(cov)), 1),
        }
        summary[f"{split} [round trip th->kr->th]"] = {
            "rows": len(rows),
            "chrf": round(sacrebleu.corpus_chrf(rt_hyp, [gold]).score, 2),
            "exact_match_pct": round(100 * rt_exact / max(1, len(rows)), 1),
        }
        for key in (f"{split} [kr2th]", f"{split} [round trip th->kr->th]"):
            print(f"=== {key} ===")
            for k, v in summary[key].items():
                print(f"    {k:34} {v}")
            print()

    with open("outputs_rules_eval.json", "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2, ensure_ascii=False)
    print("wrote outputs_rules_eval.json")


if __name__ == "__main__":
    main()
